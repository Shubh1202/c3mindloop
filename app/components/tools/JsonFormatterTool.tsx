const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

function jsonToTypeScript(val: any, interfaceName = 'RootObject'): string {
  const interfaces: string[] = [];
  function parse(name: string, obj: any): string {
    if (obj === null) return 'any';
    if (Array.isArray(obj)) {
      const type = obj.length > 0 ? parse(name, obj[0]) : 'any';
      return `${type}[]`;
    }
    if (typeof obj === 'object') {
      const cleanName = capitalize(name.replace(/[^a-zA-Z0-9]/g, ''));
      let str = `interface ${cleanName} {\n`;
      for (const key of Object.keys(obj)) {
        const nestedName = cleanName + capitalize(key);
        const propType = parse(nestedName, obj[key]);
        str += `  ${key}: ${propType};\n`;
      }
      str += '}';
      interfaces.push(str);
      return cleanName;
    }
    return typeof obj;
  }
  parse(interfaceName, val);
  const uniqueInterfaces: string[] = [];
  const seen = new Set<string>();
  for (const item of interfaces.reverse()) {
    const match = item.match(/interface (\w+)/);
    if (match) {
      const name = match[1];
      if (!seen.has(name)) {
        seen.add(name);
        uniqueInterfaces.push(item);
      }
    }
  }
  return uniqueInterfaces.join('\n\n');
}

function jsonToGo(val: any, structName = 'AutoGenerated'): string {
  const structs: string[] = [];
  function parse(name: string, obj: any): string {
    if (obj === null) return 'interface{}';
    if (Array.isArray(obj)) {
      const type = obj.length > 0 ? parse(name, obj[0]) : 'interface{}';
      return `[]${type}`;
    }
    if (typeof obj === 'object') {
      const cleanName = capitalize(name.replace(/[^a-zA-Z0-9]/g, ''));
      let str = `type ${cleanName} struct {\n`;
      for (const key of Object.keys(obj)) {
        const nestedName = cleanName + capitalize(key);
        const goField = capitalize(key);
        const propType = parse(nestedName, obj[key]);
        str += `\t${goField} ${propType} \`json:"${key}"\`\n`;
      }
      str += '}';
      structs.push(str);
      return cleanName;
    }
    if (typeof obj === 'number') {
      return Number.isInteger(obj) ? 'int' : 'float64';
    }
    if (typeof obj === 'boolean') return 'bool';
    return 'string';
  }
  parse(structName, val);
  const uniqueStructs: string[] = [];
  const seen = new Set<string>();
  for (const item of structs.reverse()) {
    const match = item.match(/type (\w+)/);
    if (match) {
      const name = match[1];
      if (!seen.has(name)) {
        seen.add(name);
        uniqueStructs.push(item);
      }
    }
  }
  return uniqueStructs.join('\n\n');
}

function flattenObject(ob: any): any {
  const toReturn: any = {};
  for (const i in ob) {
    if (!ob.hasOwnProperty(i)) continue;
    if ((typeof ob[i]) === 'object' && ob[i] !== null) {
      const flatObject = flattenObject(ob[i]);
      for (const x in flatObject) {
        if (!flatObject.hasOwnProperty(x)) continue;
        toReturn[i + '.' + x] = flatObject[x];
      }
    } else {
      toReturn[i] = ob[i];
    }
  }
  return toReturn;
}

function jsonToCSV(val: any): string {
  const arr = Array.isArray(val) ? val : [val];
  const flatArray = arr.map(item => flattenObject(item));
  const headers = Array.from(new Set(flatArray.flatMap(item => Object.keys(item))));
  if (headers.length === 0) return '';
  const csvRows = [
    headers.join(','),
    ...flatArray.map(row => {
      return headers.map(header => {
        const cell = row[header] === undefined || row[header] === null ? '' : row[header];
        const cellStr = typeof cell === 'object' ? JSON.stringify(cell) : String(cell);
        const escaped = cellStr.replace(/"/g, '""');
        return `"${escaped}"`;
      }).join(',');
    })
  ];
  return csvRows.join('\n');
}

